// Diagram frame: the one wrapper every signature diagram uses (the DIAGRAM CONTRACT in docs/design-language.md).
// A diagram kind supplies: metrics(data), staticSvg(data), controlsHtml(id, metrics, data), tablesHtml(data, metrics),
// verify(data, bodyHtml) and a browser mount(). This file only assembles the figure, so every diagram has the same
// frame, caption and data hooks.
import { html, raw, jsonScript } from '../scripts/lib/html.mjs';
import * as tracerField from './assets/diagrams/tracer-field.js';
import * as stackMap from './assets/diagrams/stack-map.js';
import * as pleromaMap from './assets/diagrams/pleroma-map.js';

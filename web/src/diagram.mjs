const KINDS = {
  'tracer-field': tracerField, 'stack-map': stackMap, 'pleroma-map': pleromaMap,
  'pleroma-superposition': pleromaSuper, 'pleroma-capacity': pleromaCap, 'latency-bars': latencyBars, 'holodb-store': holodbStore,
  'evalapp-gate': evalappGate, 'algformer-cost': algformerCost, 'holovoxel-lod': holovoxelLod, 'prose-pipeline': prosePipeline,
  'round-timeline': roundTimeline, 'slot-grow': slotGrow, 'layer-stack': layerStack, 'size-bars': sizeBars, 'design-effect': designEffect,
  'superposition-scene': superpositionScene, 'coverage-meter': coverageMeter, 'blazier-boot': blazierBoot, 'hologenome-scores': hologenomeScores,
};

export function diagramModule(kind) {
  const k = KINDS[kind];
  if (!k) throw new Error('unknown diagram kind ' + kind);
  return k;
}

const CAPTION = (data) => html`Generated by running the published ${data.package.id} package (release <span data-gen="version">${data.package.version}</span>). Every number is the package's own output.`;

export function diagramFigure({ id, kind, title, lede, data, stageLabel, caption, variant, level = 2 }) {
  const mod = diagramModule(kind);
  const m = mod.metrics(data);
  const ui = mod.controlsHtml(id, m, data);
  const H = `h${level}`;
  const head = title ? raw(`<div class="fig-head"><${H}>${html`${title}`}</${H}><p>${html`${lede}`}</p></div>`) : '';
  return {
    metrics: m,
    html: html`<figure class="fig${variant ? ' ' + variant : ''}" data-diagram="${kind}" data-diagram-id="${id}">
  ${head}
  <div class="fig-body">
    ${raw(ui.tabs)}
    ${mod.interactiveStage === false ? html`<div class="dia-stage" id="${id}-stage">${raw(mod.staticSvg(data))}</div>` : html`<div class="dia-stage" id="${id}-stage" tabindex="0" role="group" aria-label="${stageLabel}">${raw(mod.staticSvg(data))}</div>`}
    ${raw(ui.controls)}
    ${raw(mod.tablesHtml(data, m))}
    <script type="application/json" data-diagram-data>${raw(jsonScript(data))}</script>
  </div>
  <figcaption class="fig-cap">${caption ?? CAPTION(data)}</figcaption>
</figure>`,
  };
}
